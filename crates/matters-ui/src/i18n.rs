//! Translation (#75): Matters' strings in the user's language, through Qt
//! Linguist (decided on #75).
//!
//! QML marks its strings with `qsTr`. The strings Rust shows are declared
//! in [`crate::strings`], each as
//! `QT_TRANSLATE_NOOP("Matters", "literal")` (or `QT_TRANSLATE_N_NOOP`
//! for one with a count): `lupdate` reads that file with its C++ parser,
//! which knows those calls, so every literal lands in the catalog
//! (`translations/matters.ts`). A [`Text`] is translated when it is used:
//! [`Text::text`], [`Text::fill`] for `%1`, `%2`…, [`Text::count`] for
//! `%n`.
//!
//! The catalogs built into Matters (`translations/matters_<lang>.ts`,
//! compiled by `build.rs`) are registered with [`register_catalogs`], and
//! the one for the system's languages installed by
//! [`install_system_translation`].

use std::ffi::{c_char, c_int, CStr, CString};

extern "C" {
    // cpp/translations.cpp
    fn matters_add_catalog(name: *const c_char, data: *const u8, size: c_int);
    fn matters_install_system_translation();
    fn matters_use_catalog(name: *const c_char) -> bool;
    fn matters_translate(
        context: *const c_char,
        source: *const c_char,
        disambiguation: *const c_char,
        n: c_int,
    ) -> *mut c_char;
    fn matters_free_text(text: *mut c_char);
}

mod built {
    // Generated by build.rs: `CATALOGS: &[(&str, &[u8])]`.
    include!(concat!(env!("OUT_DIR"), "/catalogs.rs"));
}

/// A string Matters shows, translated when used.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Text {
    context: &'static str,
    source: &'static str,
    disambiguation: &'static str,
    plural: bool,
}

/// Declare `source`, in `context`, for translation (Qt's macro of the same
/// name, which `lupdate` looks for).
#[allow(non_snake_case)]
pub const fn QT_TRANSLATE_NOOP(context: &'static str, source: &'static str) -> Text {
    Text {
        context,
        source,
        disambiguation: "",
        plural: false,
    }
}

/// Declare `source`, in `context`, with `comment` telling it apart from the
/// same words meaning something else.
#[allow(non_snake_case)]
pub const fn QT_TRANSLATE_NOOP3(
    context: &'static str,
    source: &'static str,
    comment: &'static str,
) -> Text {
    Text {
        context,
        source,
        disambiguation: comment,
        plural: false,
    }
}

/// Declare `source`, with a count (`%n`), for translation.
#[allow(non_snake_case)]
pub const fn QT_TRANSLATE_N_NOOP(context: &'static str, source: &'static str) -> Text {
    Text {
        context,
        source,
        disambiguation: "",
        plural: true,
    }
}

impl Text {
    /// The text in the user's language, or as declared.
    pub fn text(self) -> String {
        debug_assert!(!self.plural, "{:?} needs a count", self.source);
        translate(self.context, self.source, self.disambiguation, -1)
    }

    /// The text with `%1`, `%2`… filled with `args` ([`fill`]).
    pub fn fill(self, args: &[&str]) -> String {
        fill(&self.text(), args)
    }

    /// The text in the plural form for `n`, with `%n` filled, then
    /// `%1`, `%2`… with `args`.
    pub fn count_fill(self, n: i64, args: &[&str]) -> String {
        fill(&self.count(n), args)
    }

    /// The text in the plural form for `n`, with `%n` filled.
    pub fn count(self, n: i64) -> String {
        debug_assert!(self.plural, "{:?} has no count", self.source);
        let n = i32::try_from(n).unwrap_or(i32::MAX);
        translate(self.context, self.source, self.disambiguation, n)
    }

    /// The text as declared, untranslated.
    pub fn source(self) -> &'static str {
        self.source
    }
}

/// `source`, in `context`, in the user's language (or `source` itself when
/// there is no translation). `n` picks a plural form and fills `%n`; -1
/// when the text has none.
fn translate(context: &str, source: &str, disambiguation: &str, n: i32) -> String {
    let cstr = |s: &str| CString::new(s).expect("text without NUL");
    let (context, source, disambiguation) = (cstr(context), cstr(source), cstr(disambiguation));
    // SAFETY: the arguments are NUL-terminated strings that outlive the
    // call; the result is a NUL-terminated string the callee allocated,
    // read once and handed back to be freed.
    unsafe {
        let text = matters_translate(
            context.as_ptr(),
            source.as_ptr(),
            disambiguation.as_ptr(),
            n,
        );
        let out = CStr::from_ptr(text).to_string_lossy().into_owned();
        matters_free_text(text);
        out
    }
}

/// `text` with `%1`, `%2`… replaced by `args`, in one pass (an argument
/// that contains `%2` isn't filled again), as Qt's `QString::arg` does.
pub fn fill(text: &str, args: &[&str]) -> String {
    let mut out = String::with_capacity(text.len());
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '%' {
            if let Some(digit) = chars.peek().and_then(|d| d.to_digit(10)) {
                if let Some(arg) = digit.checked_sub(1).and_then(|i| args.get(i as usize)) {
                    chars.next();
                    out.push_str(arg);
                    continue;
                }
            }
        }
        out.push(c);
    }
    out
}

/// Make the catalogs built into Matters available. Call once, before
/// [`install_system_translation`].
pub fn register_catalogs() {
    for (name, data) in built::CATALOGS {
        let name = CString::new(*name).expect("catalog name without NUL");
        let size = c_int::try_from(data.len()).expect("a catalog under 2 GB");
        // SAFETY: the name is copied by the callee; the data is static, so
        // it outlives every translator that reads it.
        unsafe { matters_add_catalog(name.as_ptr(), data.as_ptr(), size) };
    }
}

/// Translate into the first of the system's languages that Matters has a
/// catalog for. Call once the application exists.
pub fn install_system_translation() {
    // SAFETY: no arguments; the application exists.
    unsafe { matters_install_system_translation() }
}

/// Use catalog `name` (`""` for none) and translate the open windows again.
/// False when there is no such catalog.
pub fn use_catalog(name: &str) -> bool {
    let name = CString::new(name).expect("catalog name without NUL");
    // SAFETY: the name is a NUL-terminated string for the call.
    unsafe { matters_use_catalog(name.as_ptr()) }
}

/// The names of the catalogs built into Matters.
pub fn catalog_names() -> Vec<&'static str> {
    built::CATALOGS.iter().map(|(name, _)| *name).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn arguments_fill_their_places_once() {
        assert_eq!(fill("Reminder for %1", &["09:00"]), "Reminder for 09:00");
        assert_eq!(fill("%2 before %1", &["a", "b"]), "b before a");
        assert_eq!(
            fill("%1 and %2", &["%2", "x"]),
            "%2 and x",
            "not filled again"
        );
        assert_eq!(fill("100% done", &[]), "100% done");
        assert_eq!(fill("%3 missing", &["a"]), "%3 missing");
        assert_eq!(fill("%0 stays", &["a"]), "%0 stays");
        assert_eq!(fill("ends with %", &["a"]), "ends with %");
    }

    #[test]
    fn untranslated_text_is_itself_with_n_filled() {
        const OPEN: Text = QT_TRANSLATE_NOOP("Tests", "Open");
        const TASKS: Text = QT_TRANSLATE_N_NOOP("Tests", "%n tasks");
        const FOR: Text = QT_TRANSLATE_NOOP("Tests", "Reminder for %1");
        assert_eq!(OPEN.text(), "Open");
        assert_eq!(TASKS.count(3), "3 tasks");
        assert_eq!(FOR.fill(&["09:00"]), "Reminder for 09:00");
        assert_eq!(FOR.source(), "Reminder for %1");
    }
}
